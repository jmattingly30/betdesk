// Node version of build_apps_script.ps1 (same output): node build_apps_script.js
const fs = require('fs'), path = require('path');
const root = __dirname, out = path.join(root, 'apps_script');
const mods = ['util', 'config', 'data', 'projection', 'projection_v2', 'projection_eff', 'montecarlo', 'game', 'odds', 'playlog'];
let s = '// GENERATED by build_apps_script.ps1 from src/*.js - edit those files, not this one.\n'
  + 'var __MODULES = {}, __LOADED = {};\n'
  + 'function __define(name, fn) { __MODULES[name] = fn; }\n'
  + 'function __require(name) {\n'
  + "  name = String(name).replace(/^.*\\//, '').replace(/\\.js$/, '');\n"
  + '  if (__LOADED[name]) return __LOADED[name].exports;\n'
  + "  if (!__MODULES[name]) throw new Error('no module ' + name);\n"
  + '  var m = { exports: {} }; __LOADED[name] = m; __MODULES[name](m, m.exports, __require); return m.exports;\n'
  + '}\n';
for (const m of mods) s += `\n__define('${m}', function (module, exports, require) {\n${fs.readFileSync(path.join(root, 'src', m + '.js'), 'utf8').trimEnd()}\n});\n`;
fs.writeFileSync(path.join(out, 'Bundle.gs'), s);
fs.copyFileSync(path.join(root, 'public', 'index.html'), path.join(out, 'Index.html'));
// plain-text copy: file viewers run .html as a page (blank outside Apps Script), so J copies the code from this one
fs.copyFileSync(path.join(root, 'public', 'index.html'), path.join(out, 'Index.html.txt'));
console.log(`Built apps_script/: Bundle.gs (${fs.statSync(path.join(out, 'Bundle.gs')).size} bytes), Index.html`);
